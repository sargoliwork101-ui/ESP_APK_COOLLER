static const uint8_t _rcon[11]={0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static inline uint8_t _xt(uint8_t a){return (uint8_t)((a<<1)^((a&0x80)?0x1b:0));}
static inline uint8_t _mul(uint8_t a,uint8_t b){uint8_t r=0;for(int i=0;i<8;i++){if(b&1)r^=a;bool h=(a&0x80)!=0;a=(uint8_t)(a<<1);if(h)a^=0x1b;b>>=1;}return r;}
static void _ks(const uint8_t* k, uint8_t* rk){
  memcpy(rk,k,16);
  for(int i=1;i<=10;i++){
    uint8_t t[4]={_sbox[rk[16*i-3]],_sbox[rk[16*i-2]],_sbox[rk[16*i-1]],_sbox[rk[16*i-4]]};
    t[0]^=_rcon[i];
    for(int j=0;j<4;j++) rk[16*i+j]=rk[16*(i-1)+j]^t[j];
    for(int j=4;j<16;j++) rk[16*i+j]=rk[16*i+j-4]^rk[16*(i-1)+j];
  }
}
static void _sb(uint8_t* s){for(int i=0;i<16;i++)s[i]=_sbox[s[i]];}
static void _isb(uint8_t* s){for(int i=0;i<16;i++)s[i]=_isbox[s[i]];}
static void _sr(uint8_t* s){
  uint8_t t;
  t=s[1];s[1]=s[5];s[5]=s[9];s[9]=s[13];s[13]=t;
  t=s[2];s[2]=s[10];s[10]=t; t=s[6];s[6]=s[14];s[14]=t;
  t=s[3];s[3]=s[15];s[15]=s[11];s[11]=s[7];s[7]=t;
}
